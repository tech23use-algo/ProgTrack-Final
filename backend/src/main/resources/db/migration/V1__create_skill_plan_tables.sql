CREATE TABLE skill_plans (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    skill VARCHAR(80) NOT NULL,
    days INTEGER NOT NULL CHECK (days BETWEEN 1 AND 365),
    hours_per_day NUMERIC(4, 2) NOT NULL CHECK (hours_per_day BETWEEN 0.5 AND 12),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_skill_plans_user_created
    ON skill_plans (user_id, created_at DESC);

CREATE TABLE plan_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id UUID NOT NULL REFERENCES skill_plans (id) ON DELETE CASCADE,
    day_order INTEGER NOT NULL,
    day_number INTEGER NOT NULL CHECK (day_number BETWEEN 1 AND 365),
    title VARCHAR(200) NOT NULL,
    goal TEXT NOT NULL,
    CONSTRAINT uq_plan_days_plan_day UNIQUE (plan_id, day_number),
    CONSTRAINT uq_plan_days_plan_order UNIQUE (plan_id, day_order)
);

CREATE TABLE plan_tasks (
    id UUID PRIMARY KEY,
    plan_day_id BIGINT NOT NULL REFERENCES plan_days (id) ON DELETE CASCADE,
    task_order INTEGER NOT NULL,
    title VARCHAR(240) NOT NULL,
    description TEXT NOT NULL,
    estimated_minutes INTEGER NOT NULL CHECK (estimated_minutes > 0),
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMPTZ,
    CONSTRAINT uq_plan_tasks_day_order UNIQUE (plan_day_id, task_order)
);

CREATE INDEX idx_plan_tasks_day ON plan_tasks (plan_day_id);
